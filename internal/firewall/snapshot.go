package firewall

import (
	"crypto/sha256"
	"encoding/hex"
	"regexp"
	"strings"
)

var chainCounters = regexp.MustCompile(`\[[0-9]+:[0-9]+\]`)
var ruleCounters = regexp.MustCompile(`(^|\s)-c\s+[0-9]+\s+[0-9]+(\s|$)`)

func SnapshotID(raw []byte) string {
	var canonical strings.Builder
	for _, line := range strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "# Generated by iptables-save") || strings.HasPrefix(line, "# Completed on") {
			continue
		}
		if strings.HasPrefix(line, "[") {
			if end := strings.Index(line, "]"); end > 0 && strings.HasPrefix(strings.TrimSpace(line[end+1:]), "-A ") {
				line = strings.TrimSpace(line[end+1:])
			}
		}
		line = chainCounters.ReplaceAllString(line, "[0:0]")
		line = ruleCounters.ReplaceAllString(line, "$1$2")
		canonical.WriteString(strings.Join(strings.Fields(line), " "))
		canonical.WriteByte('\n')
	}
	sum := sha256.Sum256([]byte(canonical.String()))
	return hex.EncodeToString(sum[:])
}
