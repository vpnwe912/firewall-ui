package firewall

import (
	"strings"
	"testing"
)

const sample = `*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
-A INPUT -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A INPUT -p tcp -m set --match-set admin_ips src -m tcp --dport 22 -m comment --comment "SSH admin" -j ACCEPT
-A INPUT -i fwbr+ -j CT --zone 1
COMMIT
`

func TestParsePreservesUnsupported(t *testing.T) {
	r := Parse(sample)
	if len(r.Rules) != 2 {
		t.Fatalf("rules=%d", len(r.Rules))
	}
	if len(r.Unsupported) != 1 {
		t.Fatalf("unsupported=%d", len(r.Unsupported))
	}
	if r.Rules[1].Source.Type != "ipset" || r.Rules[1].Comment != "SSH admin" {
		t.Fatalf("unexpected rule: %#v", r.Rules[1])
	}
	rendered, err := Render(r)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(rendered, "-A INPUT -i fwbr+ -j CT --zone 1") {
		t.Fatal("unsupported rule was not preserved")
	}
}
func TestParseIPTablesSaveCounterPrefix(t *testing.T) {
	r := Parse("*filter\n:INPUT ACCEPT [12:345]\n[1355:468204] -A INPUT -p tcp -m set --match-set WhiteIP src -m tcp --dport 22 -m comment --comment \"SSH Admin\" -j ACCEPT\nCOMMIT\n")
	if len(r.Rules) != 1 {
		t.Fatalf("rules=%d unsupported=%d", len(r.Rules), len(r.Unsupported))
	}
	if r.Rules[0].Packets != 1355 || r.Rules[0].Bytes != 468204 {
		t.Fatalf("counters=%d:%d", r.Rules[0].Packets, r.Rules[0].Bytes)
	}
	if r.Rules[0].Source.Type != "ipset" || r.Rules[0].DestPorts[0].From != 22 {
		t.Fatalf("rule=%#v", r.Rules[0])
	}
}

func TestSnapshotIgnoresTimestampsAndCounters(t *testing.T) {
	first := []byte("# Generated by iptables-save on date one\n*filter\n:INPUT ACCEPT [10:20]\n[2:30] -A INPUT -p tcp --dport 22 -j ACCEPT\nCOMMIT\n# Completed on date one\n")
	second := []byte("# Generated by iptables-save on date two\n*filter\n:INPUT ACCEPT [999:888]\n-A INPUT -p tcp --dport 22 -j ACCEPT\nCOMMIT\n# Completed on date two\n")
	if SnapshotID(first) != SnapshotID(second) {
		t.Fatal("dynamic counters changed snapshot")
	}
	changed := []byte("*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -p tcp --dport 23 -j ACCEPT\nCOMMIT\n")
	if SnapshotID(first) == SnapshotID(changed) {
		t.Fatal("rule change did not change snapshot")
	}
}

