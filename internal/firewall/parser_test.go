func TestExternalChainsPreserved(t *testing.T) {
	raw := `# Generated by iptables-save v1.8.11
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:PVEFW-INPUT - [0:0]
:DOCKER - [0:0]
:DOCKER-USER - [0:0]
:LIBVIRT_INP - [0:0]
:KUBE-FIREWALL - [0:0]
[10:500] -A INPUT -p tcp --dport 22 -j ACCEPT
-A INPUT -j PVEFW-INPUT
-A INPUT -j DOCKER-USER
-A DOCKER -d 172.17.0.2/32 -p tcp --dport 80 -j ACCEPT
-A DOCKER-USER -j RETURN
-A LIBVIRT_INP -p udp --dport 67 -j ACCEPT
-A KUBE-FIREWALL -m comment --comment "kubernetes firewall" -j DROP
-A FORWARD -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
COMMIT
`
	rs := Parse(raw)
	if len(rs.Unsupported) != 6 {
		t.Fatalf("expected 6 external/unsupported rules, got %d: %+v", len(rs.Unsupported), rs.Unsupported)
	}
	if len(rs.Rules) != 2 {
		t.Fatalf("expected 2 editable rules, got %d", len(rs.Rules))
	}
	out, err := Render(rs)
	if err != nil {
		t.Fatal(err)
	}
	for _, must := range []string{":PVEFW-INPUT - ", ":DOCKER - ", ":DOCKER-USER - ", ":LIBVIRT_INP - ", ":KUBE-FIREWALL - ", "-A INPUT -j PVEFW-INPUT", "-A DOCKER -d 172.17.0.2/32", "-A KUBE-FIREWALL"} {
		if !strings.Contains(out, must) {
			t.Fatalf("rendered output lost %q:\n%s", must, out)
		}
	}
}
