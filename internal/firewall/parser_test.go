func TestNATParseAndRender(t *testing.T) {
	r := Parse("*nat\n:PREROUTING ACCEPT [0:0]\n:POSTROUTING ACCEPT [0:0]\n-A PREROUTING -p tcp --dport 3389 -j DNAT --to-destination 192.0.2.100:3389\n-A POSTROUTING -s 10.0.0.0/24 -o eth0 -j MASQUERADE\nCOMMIT\n")
	if len(r.Rules) != 2 || r.Rules[0].ToAddress != "192.0.2.100" || r.Rules[0].ToPort != 3389 {
		t.Fatalf("unexpected NAT parse: %#v", r.Rules)
	}
	output, err := Render(r)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(output, "-j DNAT --to-destination 192.0.2.100:3389") || !strings.Contains(output, "-j MASQUERADE") {
		t.Fatal(output)
	}
}

func TestAliasRendering(t *testing.T) {
	r := &Ruleset{Policies: map[string]string{"filter/INPUT": "ACCEPT"}, Aliases: map[string]string{"office": "192.0.2.10/32"}, Rules: []Rule{{Table: "filter", Chain: "INPUT", Action: "ACCEPT", Source: AddressMatch{Type: "alias", Value: "office"}, Destination: AddressMatch{Type: "any"}, Protocol: "tcp", Enabled: true, Position: 1}}}
	output, err := Render(r)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(output, "-s 192.0.2.10/32") {
		t.Fatal(output)
	}
}

